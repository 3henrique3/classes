# Operadores de comparação

num1 = float(input("Informe um número: "))
num2 = float(input("Informe mais um número: "))

"""
OPERADORES COMPARAÇÃO
SÃO UTILIZADOS PARA VERIFICA REALÇÕES ENTRE
VALORES ONDE O RESULTADOR SEMPRE SERÁ VERDADEIRO
OU FALSO 

IGUAL ==
DIFERENTE !=
MAIOR QUE >
MENOR QUER <
MAIOR  OU IGUAL <=
MENOR OU IGUAL =>
"""

print(num1==num2)
print(num1 !=num2)
print(num1<num2)
print(num1>num2)
print(num1<=num2)